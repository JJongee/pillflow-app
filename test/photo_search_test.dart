import 'package:flutter_test/flutter_test.dart';
import 'package:pillflow/widgets/photo_search.dart';

void main() {
  test('사진으로 찾기: 약 이름 줄만 후보로 남긴다', () {
    final lines = [
      '○○내과의원',
      '2026-10-22 조제',
      '타이레놀정500밀리그람(아세트아미노펜)',
      '1일 3회 식후 30분',
      '베아제 정',
      'Tylenol',
      '환자 성명: 홍길동',
      '베아제정', // 위 줄과 같은 이름 → 한 번만
    ];
    expect(candidateQueries(lines), ['타이레놀정500밀리그람', '베아제정']);
  });

  test('사진으로 찾기: 함량·개수만 있는 줄은 후보가 아니다', () {
    // 실제 약 상자: 상표 글씨는 못 읽고 "500 밀리그람"만 크게 읽힌 경우 → 다른 약(아스피린 500mg)이 걸리면 안 됨
    expect(candidateQueries(['500 밀리그람', '10정', '아세트아미노펜', '500mg']), ['아세트아미노펜']);
    // 이름에 함량이 붙은 줄은 그대로 후보
    expect(candidateQueries(['타이레놀정 500밀리그람']), ['타이레놀정500밀리그람']);
  });

  test('사진으로 찾기: 후보는 최대 개수까지만', () {
    final lines = [for (var i = 0; i < 30; i++) '약이름$i'];
    expect(candidateQueries(lines, limit: 5).length, 5);
  });

  test('사진으로 찾기: 큰 글자 줄부터, 비슷한 크기는 원래 순서', () {
    // 약 상자: 분류 문구(작음) → 제품 이름(큼) → 성분(작음)
    expect(bySize([('해열진통제', 44), ('타이레놀', 170), ('아세트아미노펜', 42)]),
        ['타이레놀', '해열진통제', '아세트아미노펜']);
    // 처방전 봉투: 약 이름 크기가 비슷하면 위→아래 그대로
    expect(bySize([('타이레놀정', 58), ('베아제정', 60), ('멕시롱액', 57)]), ['타이레놀정', '베아제정', '멕시롱액']);
  });

  test('사진으로 찾기: 한두 글자 틀리게 읽어도 줄여 가며 검색', () {
    // "이"를 영문 o로 읽은 경우 → 한글 덩어리 "레놀"로도 검색
    expect(searchAttempts('타o레놀'), ['타o레놀', '레놀']);
    // "미"를 "마"로 읽은 경우 → 뒤에서부터 줄여서 "아세트아"까지
    expect(searchAttempts('아세트아마노펜'), ['아세트아마노펜', '아세트아마노', '아세트아마', '아세트아', '아세트']);
  });

  test('사진으로 찾기: 결과 중 읽은 글자와 가장 비슷한 이름을 대표로', () {
    final names = ['타이레놀8시간이알서방정', '타이레놀정500밀리그람(아세트아미노펜)', '콜드타이레놀정'];
    expect(bestMatch('타o레놀정500밀리그람', names), '타이레놀정500밀리그람(아세트아미노펜)');
    // 앞에 다른 말이 붙은 이름보다 첫 글자가 같은 이름을 대표로
    expect(bestMatch('타o레놀', ['우먼스타이레놀정', '타이레놀정500밀리그람(아세트아미노펜)']), '타이레놀정500밀리그람(아세트아미노펜)');
    // 같은 사진에 "500 밀리그람"이 있으면 함량이 맞는 제품을 대표로 (실제 타이레놀 상자 사례)
    expect(
      bestMatch('타o레놀', ['타이레놀콜드-에스정', '타이레놀정500밀리그람(아세트아미노펜)', '우먼스타이레놀정'],
          hints: ['타o레놀', '500 밀리그람', '두통발열근육통', '10정', '아세트아마노펜']),
      '타이레놀정500밀리그람(아세트아미노펜)',
    );
  });

  test('사진으로 찾기: 후보를 누르면 대표 이름(괄호 앞)으로 검색', () {
    const c = PhotoCandidate('레놀', '타이레놀정500밀리그람(아세트아미노펜)', 8, read: '타o레놀');
    expect(c.searchName, '타이레놀정500밀리그람');
    expect(c.exact, isFalse);
  });
}
